#!/usr/bin/env bash
# Writes THIRD_PARTY_LICENSES.txt: the license text of every Go module compiled into the binary,
# of every npm package bundled into the GUI page, and of the AppImage runtime with the libraries
# it links statically. Runs in the build image (make licenses); the file is embedded in the binary
# (kvm-gui licenses) and shipped in every package.
set -euo pipefail
cd "$(dirname "$0")/.."
out=THIRD_PARTY_LICENSES.txt
texts() { # the license and notice files of a folder
	local found=0
	for f in "$1"/LICENSE* "$1"/LICENCE* "$1"/COPYING* "$1"/NOTICE* "$1"/license* ; do
		[[ -f $f ]] || continue
		found=1
		echo "--- $(basename "$f")"
		cat "$f"
		echo
	done
	[[ $found == 1 ]] || { echo "no license file in $1" >&2; exit 1; }
}
{
	echo "Third-party license texts for kvm-gui. Generated by scripts/licenses.sh; do not edit."
	echo "THIRD_PARTY_NOTICES.md lists the components and where each is used."
	echo
	echo "######## Go modules compiled into the binary"
	go list -tags production -deps -f '{{with .Module}}{{.Path}} {{.Version}} {{.Dir}}{{end}}' . |
		sort -u | grep -v '^github.com/jniltinho/kvm-gui ' | while read -r path version dir; do
		echo
		echo "======== $path $version"
		texts "$dir"
	done
	echo
	echo "######## npm packages bundled into the GUI page (frontend/)"
	for pkg in vue @vue/runtime-dom @vue/runtime-core @vue/reactivity @vue/shared @wailsio/runtime tailwindcss; do
		version=$(sed -n 's/^  "version": "\(.*\)",$/\1/p' "frontend/node_modules/$pkg/package.json")
		echo
		echo "======== $pkg $version"
		if [[ $pkg == @wailsio/runtime ]]; then
			# Published without a license file; MIT, from the Wails repository: its text.
			echo "MIT (package.json), from github.com/wailsapp/wails; the Wails license text:"
			texts "$(go list -m -f '{{.Dir}}' github.com/wailsapp/wails/v3)"
		else
			texts "frontend/node_modules/$pkg"
		fi
	done
	echo
	echo "######## The AppImage runtime (in the AppImage only)"
	echo "type2-runtime ${APPIMAGE_RUNTIME_VERSION:-20251108}, unmodified; its source and that of the libraries it links"
	echo "statically (musl, libfuse under LGPL-2.1, squashfuse, zstd, zlib) are at"
	echo "https://github.com/AppImage/type2-runtime/tree/${APPIMAGE_RUNTIME_VERSION:-20251108}."
	for f in /usr/local/share/appimage-runtime-licenses/*.txt; do
		echo
		echo "======== $(basename "$f" .txt)"
		cat "$f"
	done
} >"$out"
echo "wrote $out ($(wc -l <"$out") lines)"
